package com.inboxiq.app.autoreply

import com.inboxiq.app.classify.SenderKind
import com.inboxiq.app.classify.SenderProfile
import com.inboxiq.app.data.MessageLabel
import com.inboxiq.app.reply.AutoGenerated
import com.inboxiq.app.reply.ReplyGate
import java.time.Instant
import java.time.ZoneId

/** Why an incoming text did not get an automatic reply. */
enum class Skip {
    BUILD_DISABLED, OFF, OUTSIDE_SCHEDULE, EXPIRED, NOT_DEFAULT_APP, IMPORTING, NOT_A_PERSON, GROUP, MMS, LABEL, BLOCKED,
    NEVER_TEXTED, LOOKS_AUTOMATED, JUNK_TEXT, TOO_OLD, JUST_REPLIED, SENDER_LIMIT, DAILY_CAP, BAD_MESSAGE,
}

data class Incoming(
    val address: String,
    val body: String,
    val receivedAt: Long,
    val label: MessageLabel,
    val isMms: Boolean = false,
)

/** Everything the rules need to know about the world, gathered by the caller. */
data class Facts(
    val isDefaultSmsApp: Boolean,
    val importRunning: Boolean,
    val isBlocked: Boolean,
    /** Texts the user wrote to this number (not counting our own automatic ones, nor bare STOP/YES). */
    val sentToBefore: Int,
    val isSavedContact: Boolean,
    val lastAutoReplyAt: Long,
    val sentToday: Int,
)

/** The recipient and timing rules, as one pure function. See docs/AUTO_RESPONDER.md. */
object AutoReplyPolicy {
    const val MAX_AGE_MS = 5 * 60_000L
    const val LOOP_WINDOW_MS = 60_000L

    fun dayKey(now: Long, zone: ZoneId): String = Instant.ofEpochMilli(now).atZone(zone).toLocalDate().toString()

    /** null = send. */
    fun evaluate(buildEnabled: Boolean, c: AutoReplyConfig, msg: Incoming, f: Facts, now: Long, zone: ZoneId): Skip? {
        if (!buildEnabled) return Skip.BUILD_DISABLED
        if (!c.enabled) return Skip.OFF
        if (c.validate() != null) return Skip.BAD_MESSAGE
        if (c.untilMillis != 0L && now >= c.untilMillis) return Skip.EXPIRED
        if (!c.withinSchedule(now, zone)) return Skip.OUTSIDE_SCHEDULE
        if (!f.isDefaultSmsApp) return Skip.NOT_DEFAULT_APP
        if (f.importRunning) return Skip.IMPORTING
        if (msg.isMms || ReplyGate.isBlankOrPlaceholder(msg.body)) return Skip.MMS
        if (ReplyGate.isGroupAddress(msg.address)) return Skip.GROUP
        val kind = SenderProfile.of(msg.address).kind
        if (kind != SenderKind.PHONE && kind != SenderKind.INTL_PHONE) return Skip.NOT_A_PERSON
        if (msg.label != MessageLabel.PERSONAL && msg.label != MessageLabel.WORK) return Skip.LABEL
        if (f.isBlocked) return Skip.BLOCKED
        if (f.sentToBefore < 1 && !f.isSavedContact) return Skip.NEVER_TEXTED
        if (AutoGenerated.looksAutomated(msg.body)) return Skip.LOOKS_AUTOMATED
        if (ReplyGate.textCheck(msg.body, msg.address, f.sentToBefore, f.isSavedContact || f.sentToBefore > 0) != null) return Skip.JUNK_TEXT
        if (now - msg.receivedAt > MAX_AGE_MS || msg.receivedAt - now > MAX_AGE_MS) return Skip.TOO_OLD
        if (f.lastAutoReplyAt != 0L && now - f.lastAutoReplyAt < LOOP_WINDOW_MS) return Skip.JUST_REPLIED
        if (f.lastAutoReplyAt != 0L && now - f.lastAutoReplyAt < c.effectivePerSenderMs) return Skip.SENDER_LIMIT
        if (f.sentToday >= c.effectiveDailyCap) return Skip.DAILY_CAP
        return null
    }
}
