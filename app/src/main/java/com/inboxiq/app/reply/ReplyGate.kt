/**
 * The "when NOT to suggest" rules, in one place. Everything that must never get a one-tap reply is
 * decided here, before any wording is chosen. Pure Kotlin.
 */
object ReplyGate {

    private val I = RegexOption.IGNORE_CASE
    private val junkLabels = setOf(MessageLabel.PROMO, MessageLabel.SPAM, MessageLabel.SCAM, MessageLabel.OTP_2FA)

    /** A person asking for a verification code is the classic account-takeover; offer nothing, not even "no". */
    private val asksForCode = Regex(
        "\\b(send|give|share|tell|read|forward|text|screenshot|show)\\b.{0,30}\\b(code|otp|pin|passcode|password|verification|security code|2fa)\\b|\\b(code|otp|pin|passcode|password)\\b.{0,20}\\b(you (just )?(got|received|get))\\b|\\bthe (code|pin|otp) (you|that you)\\b",
        I,
    )

    private val identityProbe = Regex(
        "\\bwho is this\\b|\\bis this [a-z]+\\s*\\?|\\bwrong number\\b|\\bdo you remember me\\b|\\bhey stranger\\b|\\bnew number\\b|\\bsave my number\\b|\\bi got your number\\b|\\bfound your number\\b|\\bwe met\\b|\\bremember me\\b",
        I,
    )

    private val placeholder = Regex("^\\s*(\\[?\\s*mms( message)?\\s*\\]?|<?image>?|\\(?no (text|subject)\\)?|\\[?attachment\\]?|\\[?photo\\]?|\\[?image\\]?|\\[?video\\]?|\\[?audio\\]?)\\s*$", I)

    fun isGroupAddress(address: String): Boolean =
        address.contains(',') || address.contains(';') || address.contains('~') || address.trim().split(Regex("\\s+")).count { it.any(Char::isDigit) } > 1

    fun isBlankOrPlaceholder(body: String): Boolean = body.isBlank() || placeholder.matches(body)

    /** Label-level and sender-level checks. null = fine so far. */
    fun senderCheck(address: String, labels: Collection<MessageLabel>): Suppression? {
        if (labels.any { it in junkLabels }) return Suppression.JUNK_LABEL
        if (isGroupAddress(address)) return Suppression.GROUP_OR_SYSTEM
        val kind = SenderProfile.of(address).kind
        return when (kind) {
            SenderKind.PHONE, SenderKind.INTL_PHONE -> null
            else -> Suppression.AUTOMATED_SENDER
        }
    }

    /** Text-level checks on one message. null = fine. */
    fun textCheck(body: String, address: String, replies: Int, known: Boolean): Suppression? {
        if (AutoGenerated.looksAutomated(body)) return Suppression.AUTO_GENERATED
        if (asksForCode.containsMatchIn(body)) return Suppression.ASKS_FOR_CODE
        if (OtpExtractor.extract(body, 0L) != null) return Suppression.OTP_OR_CODE
        val sender = SenderProfile.of(address)
        val verdict = TriageEngine.rulesOnly(body, sender, replies)
        when (verdict.label) {
            MessageLabel.OTP_2FA -> return Suppression.OTP_OR_CODE
            MessageLabel.SCAM, MessageLabel.PROMO, MessageLabel.SPAM -> return Suppression.JUNK_TEXT
            else -> Unit
        }
        val stranger = Relationship.of(sender, replies) == Relationship.NONE && !known
        if (stranger) {
            if (IntentClassifier.hasLink(body) || IntentClassifier.hasLocation(body)) return Suppression.UNKNOWN_SENDER_LINK
            if (identityProbe.containsMatchIn(body) || verdict.hints.isNotEmpty()) return Suppression.UNKNOWN_SENDER_PROBE
        }
        return null
    }
}

/** Text that a machine wrote, or that signs off a conversation: nobody should auto-answer it. Shared with the auto-responder. */
object AutoGenerated {
    private val re = Regex(
        "\\b(auto[- ]?repl(y|ied)|automatic(ally)? (repl(y|ied)|response|message|generated|sent)|automated (message|repl(y|ies)|response|text|notification)|do not repl(y)?|don'?t repl(y)?|no[- ]?repl(y)?|this is an? (auto|automated|automatic)|unsubscribe|reply stop|text stop|send stop|stop to (opt|end|cancel|unsub|quit)|reply (help|end|quit|cancel) |out of office|out-of-office|sent automatically|message and data rates|msg ?& ?data|msg and data|currently unavailable|i('| a)m currently (away|out|unavailable|driving)|i('| a)m (busy|driving|away|in a meeting|unavailable)\\b.{0,50}\\b(repl(y|ied)|respond|get back|call)|will (repl(y|ied)|respond|get back to you) (to you )?(later|when i can|as soon as|shortly|soon))\\b",
        RegexOption.IGNORE_CASE,
    )

    /** Opt-out keywords as carriers and bots write them: upper case, or the whole text. */
    private val shoutedStop = Regex("\\bSTOP(ALL)?\\b")

    fun looksAutomated(text: String): Boolean =
        re.containsMatchIn(text) || shoutedStop.containsMatchIn(text) || text.trim().trimEnd('.', '!').equals("stop", ignoreCase = true)
}
