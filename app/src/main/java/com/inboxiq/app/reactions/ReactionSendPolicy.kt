package com.inboxiq.app.reactions

import com.inboxiq.app.classify.SenderProfile
import com.inboxiq.app.data.MessageEntity
import com.inboxiq.app.data.ReactionEntity
import com.inboxiq.app.data.ReactionKey
import com.inboxiq.app.inbox.OtpExtractor
import com.inboxiq.app.reply.AutoGenerated
import com.inboxiq.app.reply.ReplyGate
import com.inboxiq.app.reply.Suppression

/**
 * Whether a reaction to a message may go out as a text at all. When it may not, the reaction is kept on the phone
 * and no send option is shown. Built on the rules the smart-reply feature already uses ([ReplyGate], [SenderProfile],
 * [OtpExtractor]) so the two features cannot disagree about who is a person.
 */
object ReactionSendPolicy {
    enum class PrivateReason {
        /** InboxIQ is not the default SMS app, so it may not send. */
        NOT_DEFAULT_APP,
        /** A group address. Group picture messages are filed under the sender's own conversation, so a reply would reach one person. */
        GROUP,
        /** A picture message, or one still waiting for its pictures: the quote would be wrong or empty. */
        MMS_MESSAGE,
        /** Short code, alphanumeric sender, toll-free number or email gateway: a reply can trigger opt-out or billing handling. */
        AUTOMATED_SENDER,
        /** Filed as promo, spam, scam, one-time code or transaction. */
        JUNK_LABEL,
        /** The text is, or contains, a one-time code. It is never quoted. */
        ONE_TIME_CODE,
        /** The text reads like a machine wrote it (opt-out keywords, auto-replies). */
        AUTOMATED_TEXT,
        /** Nothing to quote. */
        NO_TEXT,
    }

    /** Null when the reaction may be sent as a text. */
    fun privateReason(message: MessageEntity, canSend: Boolean): PrivateReason? {
        if (!canSend) return PrivateReason.NOT_DEFAULT_APP
        if (ReactionKey.isMms(message)) return PrivateReason.MMS_MESSAGE
        if (message.body.isBlank()) return PrivateReason.NO_TEXT
        when (ReplyGate.senderCheck(message.address, listOf(message.label))) {
            Suppression.GROUP_OR_SYSTEM -> return PrivateReason.GROUP
            Suppression.JUNK_LABEL -> return PrivateReason.JUNK_LABEL
            null -> Unit
            else -> return PrivateReason.AUTOMATED_SENDER
        }
        if (!SenderProfile.of(message.address).isPersonLike) return PrivateReason.AUTOMATED_SENDER
        if (OtpExtractor.extract(message.body, message.timestamp) != null) return PrivateReason.ONE_TIME_CODE
        if (AutoGenerated.looksAutomated(message.body)) return PrivateReason.AUTOMATED_TEXT
        return null
    }

    fun canSendAsText(message: MessageEntity, canSend: Boolean): Boolean = privateReason(message, canSend) == null
}

/** What the screen should do when the user picks [emoji] for a message. */
sealed interface ReactionPlan {
    /** Save the reaction; deliver it as [delivery]. */
    data class Apply(val delivery: ReactionDelivery) : ReactionPlan

    /** The same emoji again: take the reaction off, and send a removal text when [sendRemovalText]. */
    data class Remove(val sendRemovalText: Boolean) : ReactionPlan

    /** Show the send sheet first: [explainer] is true the first time, when the mode is still undecided. */
    data class Ask(val explainer: Boolean) : ReactionPlan
}

object ReactionPlanner {
    fun plan(
        message: MessageEntity,
        emoji: String,
        existing: ReactionEntity?,
        settings: ReactionSettings,
        canSend: Boolean,
    ): ReactionPlan {
        val offered = ReactionSendPolicy.canSendAsText(message, canSend)
        if (existing != null && ReactionEmoji.same(existing.emoji, emoji)) {
            return ReactionPlan.Remove(sendRemovalText = settings.sendRemovalText && existing.sentAsText && offered)
        }
        if (!offered) return ReactionPlan.Apply(ReactionDelivery.PRIVATE)
        if (!settings.explained) return ReactionPlan.Ask(explainer = true)
        return when (settings.mode) {
            ReactionMode.SEND_AS_TEXT -> ReactionPlan.Apply(ReactionDelivery.TEXT)
            ReactionMode.KEEP_PRIVATE -> ReactionPlan.Apply(ReactionDelivery.PRIVATE)
            ReactionMode.ASK -> ReactionPlan.Ask(explainer = false)
        }
    }
}
